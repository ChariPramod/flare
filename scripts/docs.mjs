// Offline documentation guard. Imports are side-effect free for tooling and tests.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

function visibleLines(markdown) {
  let fence;
  let comment = false;
  return markdown.split(/\r?\n/).map((line) => {
    const delimiter = line.match(/^ {0,3}(`{3,}|~{3,})(.*)$/);
    if (fence) {
      if (
        delimiter &&
        delimiter[1][0] === fence[0] &&
        delimiter[1].length >= fence.length &&
        !delimiter[2].trim()
      )
        fence = undefined;
      return '';
    }
    if (delimiter) {
      fence = delimiter[1];
      return '';
    }
    if (/^( {4}|\t)/.test(line)) return '';
    let output = '';
    for (let index = 0; index < line.length;) {
      if (comment) {
        const end = line.indexOf('-->', index);
        if (end === -1) break;
        comment = false;
        index = end + 3;
      } else {
        const start = line.indexOf('<!--', index);
        if (start === -1) {
          output += line.slice(index);
          break;
        }
        output += line.slice(index, start);
        comment = true;
        index = start + 4;
      }
    }
    return output;
  });
}

function decodeEntities(text) {
  const entities = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
  return text.replace(/&(#x[\da-f]+|#\d+|amp|lt|gt|quot|apos|nbsp);/gi, (match, entity) => {
    if (!entity.startsWith('#')) return entities[entity.toLowerCase()];
    const code =
      entity[1].toLowerCase() === 'x'
        ? Number.parseInt(entity.slice(2), 16)
        : Number(entity.slice(1));
    return code >= 0 && code <= 0x10ffff ? String.fromCodePoint(code) : match;
  });
}

export function githubSlug(text) {
  return decodeEntities(text.replace(/<[^>]*>/g, '').replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1'))
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc}\-\s]/gu, '')
    .replace(/\s/g, '-');
}

export function extractHeadings(markdown) {
  const lines = visibleLines(markdown);
  const used = new Set();
  const headings = [];
  for (let index = 0; index < lines.length; index++) {
    const match = lines[index].match(/^ {0,3}(#{1,6})\s+(.+?)\s*#*\s*$/);
    const setext = index > 0 && lines[index].match(/^ {0,3}(=+|-+)\s*$/) && lines[index - 1].trim();
    if (!match && !setext) continue;
    const text = match ? match[2] : lines[index - 1].trim();
    const base = githubSlug(text);
    let slug = base;
    for (let suffix = 1; used.has(slug); suffix++) slug = `${base}-${suffix}`;
    used.add(slug);
    headings.push({
      level: match ? match[1].length : lines[index].trim()[0] === '=' ? 1 : 2,
      text,
      source: match ? lines[index] : `${lines[index - 1]}\n${lines[index]}`,
      slug,
      line: match ? index + 1 : index,
    });
  }
  return headings;
}

function htmlAnchors(markdown) {
  const anchors = [];
  for (const line of visibleLines(markdown).map(withoutInlineCode)) {
    for (const match of line.matchAll(/<[^>]+\s(?:id|name)\s*=\s*(["'])(.*?)\1[^>]*>/gi))
      anchors.push(decodeEntities(match[2]));
  }
  return anchors;
}

function markdownPath(from, to) {
  return relative(dirname(from), to).split('\\').join('/');
}

export function generateCompatibility(sourcePath, canonicalPath, markdown) {
  const target = markdownPath(sourcePath, canonicalPath);
  const index = markdownPath(sourcePath, 'docs/README.md');
  const lines = [
    '<!-- Generated by scripts/docs.mjs; edit the canonical document instead. -->',
    '',
    `This document moved to [${canonicalPath}](${target}). Existing section links remain below.`,
    '',
    `Browse the [documentation index](${index}).`,
  ];
  for (const anchor of htmlAnchors(markdown)) {
    const escaped = anchor
      .replaceAll('&', '&amp;')
      .replaceAll('"', '&quot;')
      .replaceAll('<', '&lt;');
    lines.push(
      '',
      `<a id="${escaped}"></a>`,
      '',
      `[Open this section](${target}#${encodeURIComponent(anchor)}).`,
    );
  }
  for (const heading of extractHeadings(markdown)) {
    lines.push(
      '',
      heading.source,
      '',
      `[Open this section](${target}#${encodeURIComponent(heading.slug)}).`,
    );
  }
  return `${lines.join('\n')}\n`;
}

function withoutInlineCode(line) {
  return line.replace(/(`+)([\s\S]*?)\1(?!`)/g, (match) => ' '.repeat(match.length));
}

function destination(input) {
  const value = input.trimStart();
  if (value.startsWith('<')) {
    const end = value.indexOf('>');
    return end >= 0 ? value.slice(1, end) : undefined;
  }
  let depth = 0;
  for (let index = 0; index < value.length; index++) {
    if (value[index] === '\\') {
      index++;
      continue;
    }
    if (value[index] === '(') depth++;
    if (value[index] === ')') {
      if (!depth) return value.slice(0, index);
      depth--;
    }
    if (/\s/.test(value[index]) && !depth) return value.slice(0, index);
  }
  return value;
}

function referenceId(value) {
  return value.trim().replace(/\s+/g, ' ').toLowerCase();
}

export function extractLinks(markdown) {
  const lines = visibleLines(markdown).map(withoutInlineCode);
  const definitions = new Map();
  const links = [];
  for (let index = 0; index < lines.length; index++) {
    const match = lines[index].match(/^ {0,3}\[([^\]]+)\]:\s*(.+)$/);
    if (match) {
      const href = destination(match[2]);
      if (href !== undefined && !definitions.has(referenceId(match[1])))
        definitions.set(referenceId(match[1]), href);
      lines[index] = '';
    }
  }
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index];
    const pattern = /(?<!\\)\[([^\]\n]*)\](?:(\()|\[([^\]\n]*)\])?/g;
    let match;
    while ((match = pattern.exec(line))) {
      if (match[2] !== undefined) {
        const remainder = line.slice(pattern.lastIndex);
        const href = destination(remainder);
        if (href !== undefined) links.push({ href, line: index + 1 });
        // Skip the destination/title, retaining later links and their document's
        // reference definitions. Parentheses inside a bare destination balance.
        const end = remainder.indexOf(')', href?.length ?? 0);
        if (end >= 0) pattern.lastIndex += end + 1;
      } else {
        const ref = referenceId(match[3] || match[1]);
        if (definitions.has(ref)) links.push({ href: definitions.get(ref), line: index + 1 });
        else if (match[3] !== undefined) links.push({ missingReference: ref, line: index + 1 });
      }
    }
    for (const match of line.matchAll(/<(?:a|img)\b[^>]*\s(?:href|src)\s*=\s*(["'])(.*?)\1/gi))
      links.push({ href: match[2], line: index + 1 });
  }
  return links;
}

function isDocumentation(file) {
  return (
    /^(README|PROGRESS|CHANGELOG)\.md$/.test(file) ||
    (file.startsWith('docs/') && file.endsWith('.md') && !file.startsWith('docs/memory/')) ||
    file === 'docs/memory/README.md' ||
    /^(apps|packages)\/[^/]+\/README\.md$/.test(file)
  );
}

function safeFile(root, file) {
  const path = resolve(root, file);
  if (
    isAbsolute(file) ||
    file.split('/').some((part) => !part || part === '..' || part === '.') ||
    file.includes('\\') ||
    !file.endsWith('.md')
  )
    return false;
  let existing = path;
  while (!existsSync(existing)) existing = dirname(existing);
  const actual = resolve(realpathSync(existing), relative(existing, path));
  return !relative(root, actual).startsWith('..') && !isAbsolute(relative(root, actual));
}

export function checkDocumentation(root, { write = false, files } = {}) {
  root = realpathSync(root);
  files ??= execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], {
    cwd: root,
    encoding: 'utf8',
  })
    .split('\0')
    .filter(Boolean);
  const documents = [...new Set(files.filter(isDocumentation))].sort();
  const documentSet = new Set(documents);
  const errors = [];
  const manifest = JSON.parse(readFileSync(resolve(root, 'docs/redirects.json'), 'utf8'));
  if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest))
    throw new Error('docs/redirects.json must be an object of old path to canonical path');
  const baseline = JSON.parse(readFileSync(resolve(root, 'docs/legacy-anchors.json'), 'utf8'));
  if (!baseline || typeof baseline !== 'object' || Array.isArray(baseline))
    throw new Error(
      'docs/legacy-anchors.json must be an object of original path to required anchors',
    );
  const requiredAnchors = new Map();
  for (const [file, slugs] of Object.entries(baseline)) {
    if (
      !safeFile(root, file) ||
      !isDocumentation(file) ||
      file.startsWith('docs/memory/') ||
      !Array.isArray(slugs) ||
      slugs.some((slug) => typeof slug !== 'string') ||
      new Set(slugs).size !== slugs.length
    ) {
      errors.push(`Invalid historical-anchor baseline: ${file}`);
      continue;
    }
    requiredAnchors.set(file, slugs);
  }
  const anchors = new Map();
  const anchorsFor = (file) => {
    if (!anchors.has(file)) {
      const text = readFileSync(resolve(root, file), 'utf8');
      anchors.set(
        file,
        new Set([...extractHeadings(text).map(({ slug }) => slug), ...htmlAnchors(text)]),
      );
    }
    return anchors.get(file);
  };
  for (const [source, target] of Object.entries(manifest)) {
    if (
      typeof target !== 'string' ||
      !safeFile(root, source) ||
      !safeFile(root, target) ||
      source.startsWith('docs/memory/') ||
      target.startsWith('docs/memory/') ||
      !isDocumentation(source) ||
      !isDocumentation(target)
    ) {
      errors.push(`Invalid compatibility mapping: ${source}`);
      continue;
    }
    if (source === target || Object.hasOwn(manifest, target)) {
      errors.push(
        `Compatibility mappings cannot point to themselves or another compatibility file: ${source}`,
      );
      continue;
    }
    if (!documentSet.has(target) || !existsSync(resolve(root, target))) {
      errors.push(`Missing canonical document: ${target}`);
      continue;
    }
    if (!requiredAnchors.has(source)) {
      errors.push(`Missing historical-anchor baseline: ${source}`);
      continue;
    }
    const lost = requiredAnchors.get(source).filter((slug) => !anchorsFor(target).has(slug));
    if (lost.length) {
      errors.push(
        `Historical anchors missing from ${target}: ${lost.map((slug) => `#${slug}`).join(', ')}; retain explicit old IDs before regenerating ${source}`,
      );
      continue;
    }
    const expected = generateCompatibility(
      source,
      target,
      readFileSync(resolve(root, target), 'utf8'),
    );
    if (write) {
      writeFileSync(resolve(root, source), expected);
      anchors.delete(source);
    }
    if (
      !existsSync(resolve(root, source)) ||
      readFileSync(resolve(root, source), 'utf8') !== expected
    )
      errors.push(`Stale compatibility page: ${source}; run node scripts/docs.mjs --write`);
    if (!documentSet.has(source)) {
      documents.push(source);
      documentSet.add(source);
    }
  }
  for (const [file, slugs] of requiredAnchors) {
    if (!existsSync(resolve(root, file))) {
      errors.push(`Missing historical document: ${file}`);
      continue;
    }
    const lost = slugs.filter((slug) => !anchorsFor(file).has(slug));
    if (lost.length)
      errors.push(
        `Historical anchors missing from ${file}: ${lost.map((slug) => `#${slug}`).join(', ')}`,
      );
  }
  let checkedLinks = 0;
  for (const file of documents) {
    if (!existsSync(resolve(root, file))) {
      errors.push(`Missing Markdown file: ${file}`);
      continue;
    }
    for (const link of extractLinks(readFileSync(resolve(root, file), 'utf8'))) {
      const label = `${file}:${link.line}`;
      if (link.missingReference !== undefined) {
        errors.push(`${label}: missing reference [${link.missingReference}]`);
        continue;
      }
      const href = decodeEntities(link.href).replace(/\\([\\()[\] ])/g, '$1');
      if (/^[a-z][a-z\d+.-]*:/i.test(href) || href.startsWith('//')) continue;
      const hash = href.indexOf('#');
      let target;
      let fragment;
      try {
        const path = decodeURIComponent((hash >= 0 ? href.slice(0, hash) : href).split('?')[0]);
        fragment = hash >= 0 ? decodeURIComponent(href.slice(hash + 1)) : '';
        target = path ? resolve(dirname(resolve(root, file)), path) : resolve(root, file);
      } catch {
        errors.push(`${label}: invalid URL escape in ${href}`);
        continue;
      }
      const targetFile = relative(root, target).split('\\').join('/');
      checkedLinks++;
      if (targetFile.startsWith('../') || isAbsolute(targetFile)) {
        errors.push(`${label}: local link leaves the repository: ${href}`);
        continue;
      }
      if (!existsSync(target)) {
        errors.push(`${label}: missing local target ${href}`);
        continue;
      }
      if (
        fragment &&
        statSync(target).isFile() &&
        target.endsWith('.md') &&
        !anchorsFor(targetFile).has(fragment)
      )
        errors.push(`${label}: missing section #${fragment} in ${targetFile}`);
    }
  }
  return {
    errors,
    documents: documents.length,
    redirects: Object.keys(manifest).length,
    historicalAnchors: [...requiredAnchors.values()].reduce(
      (count, slugs) => count + slugs.length,
      0,
    ),
    links: checkedLinks,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (
      args.some((arg) => !['--check', '--write'].includes(arg)) ||
      (args.includes('--check') && args.includes('--write'))
    )
      throw new Error('Usage: node scripts/docs.mjs [--check | --write]');
    const result = checkDocumentation(process.cwd(), { write: args.includes('--write') });
    if (result.errors.length) {
      console.error(result.errors.join('\n'));
      process.exitCode = 1;
    } else
      console.log(
        `Documentation checks passed: ${result.documents} Markdown files, ${result.redirects} compatibility pages, ${result.links} local links, ${result.historicalAnchors} historical anchors.`,
      );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
